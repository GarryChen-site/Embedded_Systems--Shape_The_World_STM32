// dac_hal.c — Lab 15 Space Invaders, HAL version
//
// 4-bit R-2R DAC on PB0–PB3, driven via direct ODR write.
//
// WHY direct ODR (not HAL_GPIO_WritePin)?
//   Writing 4 bits simultaneously requires one 32-bit write.
//   HAL_GPIO_WritePin handles one pin at a time — four calls would interleave
//   sound samples and create glitches.  Direct GPIOB->ODR write is atomic for
//   the 4 LSBs and is perfectly valid alongside HAL code.
//
// IMPORTANT: CubeIDE must configure PB0, PB1, PB2, PB3 as GPIO_Output in the
//   IOC file (see README.md Step 4).  MX_GPIO_Init() handles the HAL init;
//   DAC_HAL_Init() only zeros the outputs.

#include "dac_hal.h"
#include "stm32f4xx_hal.h" /* GPIOB, GPIO_PIN_x — generated by CubeIDE */

// -------------------------------------------------------------------------
// DAC_HAL_Init — silence the DAC outputs
// Call after MX_GPIO_Init() has been called by CubeIDE-generated code.
// -------------------------------------------------------------------------
void DAC_HAL_Init(void) {
  // Clear PB0–PB3 (set to 0 V = silent)
  GPIOB->ODR &= ~(0x0FU);
}

// -------------------------------------------------------------------------
// DAC_HAL_Out — write a 4-bit sample to the R-2R ladder
//
// data: 0–15 (4-bit unsigned)
//   bit 0 → PB0 (LSB, smallest R-2R weight)
//   bit 3 → PB3 (MSB, largest R-2R weight)
// -------------------------------------------------------------------------
void DAC_HAL_Out(uint8_t data) {
  // Read-modify-write: preserve PB4–PB15, replace PB0–PB3
  GPIOB->ODR = (GPIOB->ODR & ~0x0FU) | ((uint32_t)(data & 0x0FU));
}
