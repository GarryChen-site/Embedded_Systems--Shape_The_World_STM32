// dac_hal.c — Lab 15 Space Invaders, HAL version
//
// 4-bit R-2R DAC on PB0, PB1, PB2, PB4, driven via direct ODR write.
//
// WHY PB4 and NOT PB3?
//   PB3 is hard-wired to SWO (Serial Wire Output / debug trace) on
//   Nucleo-F446RE. It cannot be used as a general GPIO output. PB4 (Arduino D12
//   / MISO, CN10 pin 27) is free.
//
// WHY direct ODR (not HAL_GPIO_WritePin)?
//   Writing 4 bits simultaneously requires one 32-bit write.
//   HAL_GPIO_WritePin handles one pin at a time — four calls would interleave
//   sound samples and create glitches.  Direct GPIOB->ODR write is atomic for
//   the relevant bits and is perfectly valid alongside HAL code.
//
// IMPORTANT: CubeIDE must configure PB0, PB1, PB2, PB4 as GPIO_Output in the
//   IOC file (see README.md Step 6).  MX_GPIO_Init() handles the HAL init;
//   DAC_HAL_Init() only zeros the outputs.

#include "dac_hal.h"
#include "stm32f4xx_hal.h" /* GPIOB, GPIO_PIN_x — generated by CubeIDE */

// -------------------------------------------------------------------------
// DAC_HAL_Init — silence the DAC outputs (clear PB0, PB1, PB2, PB4)
void DAC_HAL_Init(void) {
  GPIOB->ODR &= ~((1U << 0) | (1U << 1) | (1U << 2) | (1U << 4));
}

// -------------------------------------------------------------------------
// DAC_HAL_Out — write a 4-bit sample to the R-2R ladder
//
// data: 0–15 (4-bit unsigned)
//   bit 0 → PB0 (LSB, smallest R-2R weight)  ODR bit 0
//   bit 1 → PB1                               ODR bit 1
//   bit 2 → PB2                               ODR bit 2
//   bit 3 → PB4 (MSB, largest R-2R weight)    ODR bit 4  ← skips PB3 (SWO)
// -------------------------------------------------------------------------
void DAC_HAL_Out(uint8_t data) {
  // Mask: clear PB0, PB1, PB2, PB4 only; preserve all other GPIOB bits
  uint32_t odr = GPIOB->ODR & ~((1U << 0) | (1U << 1) | (1U << 2) | (1U << 4));
  // Scatter data bits into the correct ODR positions
  odr |= ((uint32_t)(data & 0x07U))             // bits[2:0] → PB2,PB1,PB0
         | (((uint32_t)(data >> 3) & 1U) << 4); // bit[3]    → PB4
  GPIOB->ODR = odr;
}
