// Game_Over — freeze display with "GAME OVER" message
// Delay100ms(2) → HAL_Delay(200U)
// =========================================================================
void Game_Over(void) {
    HAL_Delay(100U);
    SSD1306_ClearBuffer();
    SSD1306_SetCursor(2, 2);
    SSD1306_OutString("GAME OVER");
    SSD1306_SetCursor(2, 4);
    SSD1306_OutString("Nice try,");
    SSD1306_SetCursor(2, 5);
    SSD1306_OutString("Earthling!");
    SSD1306_DisplayBuffer();
    while (1);   // halt
}

// =========================================================================
// Level_Check — advance level or trigger Game Over
// Delay100ms(2) → HAL_Delay(200U)
// Delay100ms(5) → HAL_Delay(500U)
// =========================================================================
void Level_Check(void) {
    int i;
    int enemiesDead = 0;
    if (Player.life <= 0 && Player.deathCounter <= 0) Game_Over();
    for (i = 0; i < (int)numEnemies; i++) {
        if (Enemy[i].life <= 0) enemiesDead++;
        if ((Enemy[i].maxpoint[1] >= Player.y) && (Enemy[i].life > 0)) Game_Over();
    }
    if (enemiesDead == (int)numEnemies) {
        currentLevel++;
        enemyDir = (int32_t)currentLevel;
        HAL_Delay(100U);
        SSD1306_ClearBuffer();
        SSD1306_SetCursor(3, 2);
        SSD1306_OutString("LEVEL");
        SSD1306_SetCursor(10, 2);
        SSD1306_OutUDec((uint16_t)currentLevel);
        SSD1306_DisplayBuffer();
        HAL_Delay(500U);
        Enemy_Init();
        Bunker_Init();
        Player_Init();
    }
}
