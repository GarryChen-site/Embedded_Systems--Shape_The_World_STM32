//    3.3V (CN8 pin 4)       ←  CW  end (pin 3)
//    Electrical range: 0°–240° → ADC 0–4095 → player X 0–110
//
//  FIRE BUTTONS (normally-open, with external pull-down to GND):
//    PC6  (CN10 pin 13)  ← missile button  (rising edge → EXTI6)
//    PC8  (CN10 pin 3)   ← laser  button   (rising edge → EXTI8)
//
//  SOUND DAC (R-2R ladder → buzzer optional):
//    PB0  (CN8  pin 5  / Arduino A3) ← bit 0 (LSB)
//    PB1  (CN10 pin 24)              ← bit 1
//    PB2  (CN10 pin 22)              ← bit 2
//    PB4  (CN10 pin 27 / Arduino D12)← bit 3 (MSB)  [PB3 is SWO, reserved]
//
// =========================================================================
// WHAT WAS REMOVED FROM THE BARE-METAL VERSION (see SpaceInvaders_stm32.c)
// =========================================================================
//  • All peripheral register #define macros (RCC_*, GPIO*, ADC1_*, EXTI_*, ...)
