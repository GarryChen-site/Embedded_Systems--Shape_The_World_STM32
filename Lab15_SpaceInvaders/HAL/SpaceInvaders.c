// =========================================================================
// Convert — ADC 12-bit → player X position  (0 to SCREENW-PLAYERW = 0-110)
//
// Original: (66 * sample) / 4095  where 66 = 84  - PLAYERW(18)
// STM32:   (110 * sample) / 4095  where 110 = 128 - PLAYERW(18)
// =========================================================================
uint32_t Convert(uint32_t sample) {
    return (110U * sample) / 4095U;
}

