// =========================================================================
//
//  DISPLAY (SSD1306 I2C OLED 128×64):
//    PB6 (SCL)  CN10 pin 17  (Arduino D10)  ↔  SSD1306 SCL
//    PB7 (SDA)  CN10 pin 19               ↔  SSD1306 SDA
//    3.3V        CN8 pin 4                →   SSD1306 VCC
//    GND                                  →   SSD1306 GND
//
//  TRIMMING POTENTIOMETER (player ship position):
