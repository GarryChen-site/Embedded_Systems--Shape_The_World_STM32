/* FormatADC — format 12-bit value (0–4095) as "ADC: XXXX\0" into buf[10] */
static void FormatADC(uint32_t raw, char buf[10]) {
  buf[0] = 'A';
  buf[1] = 'D';
  buf[2] = 'C';
  buf[3] = ':';
  buf[4] = ' ';
  buf[9] = '\0';
  uint32_t n = raw;
  buf[8] = (char)('0' + (n % 10U));
  n /= 10U;
  buf[7] = (char)('0' + (n % 10U));
  n /= 10U;
  buf[6] = (char)('0' + (n % 10U));
  n /= 10U;
  buf[5] = (char)('0' + (n % 10U));
}
