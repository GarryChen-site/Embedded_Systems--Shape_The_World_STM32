// KEY DIFFERENCES FROM BARE-METAL ssd1306.c:
//   - No i2c.h dependency.  Uses HAL_I2C_Master_Transmit(&hi2c1, ...) instead.
//   - DevAddress = SSD1306_ADDR << 1 = 0x78 ("Target device address: The device
//     7 bits address value in datasheet must be shifted to the left before
//     calling the interface").
//   - SSD1306_Update uses a static 1025-byte tx_buf to combine the 0x40
//     control byte with the framebuffer in one call (avoids double-STOP).
//   - All other logic (framebuffer, font, draw primitives) is identical.
//
// FONT: standard 5x8 pixel ASCII, column-major, LSB=top.
//   96 characters: 0x20 (space) through 0x7F (DEL).

